using System;
using System.IO;
using System.Linq;
using HarmonyLib;
using StardewModdingAPI;
using StardewModdingAPI.Events;
using StardewValley;
using UntranslatedStardew.Core;

namespace UntranslatedStardew;

/// <summary>
/// The main entry point for Untranslated Stardew mod.
/// Intercepts item tooltips to show bilingual item names and provides search APIs.
/// </summary>
public sealed class ModEntry : Mod
{
    internal static ModEntry? Instance { get; private set; }

    public ModConfig Config { get; private set; } = null!;

    private Harmony? _harmony;
    private RawContentProvider? _contentProvider;
    private ItemNameResolver? _nameResolver;
    private UntranslatedStardewApi? _api;

    public override void Entry(IModHelper helper)
    {
        Instance = this;

        // Initialize translation helper generated by ModTranslationClassBuilder
        I18n.Init(helper.Translation);

        // Read configuration (handle null or empty fields safely)
        Config = helper.ReadConfig<ModConfig>();
        if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
        {
            Config.SecondaryLanguage = "en";
        }

        // Initialize stable API referencing resolver dynamically
        _api = new UntranslatedStardewApi(() => _nameResolver, () => Config);

        // Build initial resolver with lazy service provider
        InitializeResolver();

        // Apply Harmony patches
        try
        {
            _harmony = new Harmony(ModManifest.UniqueID);
            _harmony.PatchAll(typeof(ModEntry).Assembly);
        }
        catch (Exception ex)
        {
            Monitor.Log(I18n.Log_PatchFailed(ex.Message), LogLevel.Warn);
        }

        // Register event handlers
        helper.Events.GameLoop.GameLaunched += OnGameLaunched;
        helper.Events.Content.LocaleChanged += OnLocaleChanged;
        helper.Events.Content.AssetsInvalidated += OnAssetsInvalidated;

        string effectiveLang = _contentProvider?.EffectiveLanguage ?? Config.SecondaryLanguage;
        Monitor.Log(I18n.Log_ModLoaded(effectiveLang), LogLevel.Info);
    }

    public override object? GetApi()
    {
        return _api;
    }

    /// <summary>
    /// Formats the tooltip title using the active resolver and configuration.
    /// Called safely from TooltipPatch prefix.
    /// </summary>
    internal void FormatTooltipTitle(ref string hoverTitle, Item hoveredItem)
    {
        if (!Config.ShowSecondaryInTooltip || _nameResolver == null)
            return;

        string primaryName = hoveredItem.DisplayName;
        string? secondaryName = _nameResolver.GetSecondaryName(hoveredItem);

        hoverTitle = TooltipFormatter.FormatTitle(hoverTitle, primaryName, secondaryName, Config.SecondaryFirst);
    }

    private void OnGameLaunched(object? sender, GameLaunchedEventArgs e)
    {
        // Re-initialize to ensure ServiceProvider is bound once game content pipeline is live
        InitializeResolver();

        RegisterGenericModConfigMenu();
    }

    private void OnLocaleChanged(object? sender, LocaleChangedEventArgs e)
    {
        _nameResolver?.Invalidate();
    }

    private void OnAssetsInvalidated(object? sender, AssetsInvalidatedEventArgs e)
    {
        if (e.NamesWithoutLocale.Any(name =>
            name.IsEquivalentTo("Strings/Objects") ||
            name.IsEquivalentTo("Strings/Weapons") ||
            name.IsEquivalentTo("Strings/Tools") ||
            name.IsEquivalentTo("Strings/BigCraftables") ||
            name.IsEquivalentTo("Data/Objects") ||
            name.IsEquivalentTo("Data/Weapons") ||
            name.IsEquivalentTo("Data/Tools") ||
            name.IsEquivalentTo("Data/BigCraftables") ||
            name.IsEquivalentTo("Data/Boots") ||
            name.IsEquivalentTo("Data/hats") ||
            name.IsEquivalentTo("Data/Furniture")))
        {
            _nameResolver?.Invalidate();
        }
    }

    private void RegisterGenericModConfigMenu()
    {
        var gmcm = Helper.ModRegistry.GetApi<IGenericModConfigMenuApi>("spacechase0.GenericModConfigMenu");
        if (gmcm == null)
            return;

        gmcm.Register(
            mod: ModManifest,
            reset: () =>
            {
                Config = new ModConfig();
                InitializeResolver();
            },
            save: () =>
            {
                if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
                {
                    Config.SecondaryLanguage = "en";
                }
                Helper.WriteConfig(Config);
                InitializeResolver();
            }
        );

        gmcm.AddTextOption(
            mod: ModManifest,
            getValue: () => Config.SecondaryLanguage,
            setValue: value => Config.SecondaryLanguage = value,
            name: I18n.Config_SecondaryLanguage_Name,
            tooltip: I18n.Config_SecondaryLanguage_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.ShowSecondaryInTooltip,
            setValue: value => Config.ShowSecondaryInTooltip = value,
            name: I18n.Config_ShowSecondary_Name,
            tooltip: I18n.Config_ShowSecondary_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.SecondaryFirst,
            setValue: value => Config.SecondaryFirst = value,
            name: I18n.Config_SecondaryFirst_Name,
            tooltip: I18n.Config_SecondaryFirst_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.DiacriticInsensitiveSearch,
            setValue: value => Config.DiacriticInsensitiveSearch = value,
            name: I18n.Config_DiacriticInsensitive_Name,
            tooltip: I18n.Config_DiacriticInsensitive_Description
        );
    }

    private void InitializeResolver()
    {
        _contentProvider?.Dispose();

        string gameContentRoot = Path.Combine(Constants.GamePath, "Content");
        string? modContentRoot = DiscoverVietnamesePackContentPath();

        _contentProvider = new RawContentProvider(
            () => Game1.content?.ServiceProvider,
            gameContentRoot,
            Config.SecondaryLanguage,
            modContentRoot,
            (requested, fallback) => Monitor.Log(I18n.Log_SecondaryFallback(requested, fallback), LogLevel.Warn)
        );

        _nameResolver = new ItemNameResolver(_contentProvider);
    }

    private string? DiscoverVietnamesePackContentPath()
    {
        // 1. Try public SMAPI ModRegistry for Kou.ViethoaSV
        IModInfo? modInfo = Helper.ModRegistry.Get("Kou.ViethoaSV");
        if (modInfo != null)
        {
            string? dir = modInfo.GetType().GetProperty("DirectoryPath")?.GetValue(modInfo) as string;
            if (!string.IsNullOrEmpty(dir))
            {
                string targetContent = Path.Combine(dir, "assets", "Content");
                if (Directory.Exists(targetContent))
                    return targetContent;
            }
        }

        // 2. Fallback to standard mod folder name
        string standardFolder = Path.Combine(Constants.GamePath, "Mods", "Stardew Valley Viethoa", "assets", "Content");
        if (Directory.Exists(standardFolder))
            return standardFolder;

        return null;
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            Helper.Events.GameLoop.GameLaunched -= OnGameLaunched;
            Helper.Events.Content.LocaleChanged -= OnLocaleChanged;
            Helper.Events.Content.AssetsInvalidated -= OnAssetsInvalidated;

            _contentProvider?.Dispose();
            _contentProvider = null;
            _nameResolver = null;

            _harmony?.UnpatchAll(ModManifest.UniqueID);
            _harmony = null;
            Instance = null;
        }

        base.Dispose(disposing);
    }
}

/// <summary>
/// Minimal interface for Generic Mod Config Menu integration.
/// </summary>
public interface IGenericModConfigMenuApi
{
    void Register(IManifest mod, Action reset, Action save, bool titleScreenOnly = false);
    void AddTextOption(IManifest mod, Func<string> getValue, Action<string> setValue, Func<string> name, Func<string>? tooltip = null, string[]? allowedValues = null, Func<string, string>? formatAllowedValue = null, string? fieldId = null);
    void AddBoolOption(IManifest mod, Func<bool> getValue, Action<bool> setValue, Func<string> name, Func<string>? tooltip = null, string? fieldId = null);
}
