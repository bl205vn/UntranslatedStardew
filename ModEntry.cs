/// <summary>
/// The main entry point for Untranslated Stardew mod.
/// Intercepts item tooltips to show bilingual item names and provides search APIs.
/// </summary>
public sealed class ModEntry : Mod
{
    private const string DialoguePairsAsset = "Mods/GiaHung.UntranslatedStardew/DialoguePairs";

    internal static ModEntry? Instance { get; private set; }

    public ModConfig Config { get; private set; } = null!;
    public ItemNameResolver? Resolver => _nameResolver;
    public BilingualFontManager? FontManager => _fontManager;
    public LanguageSourceRegistry SourceRegistry { get; } = new();

    private (WeakReference<DialogueBox> Box, bool SecondaryFirst, DialogueTextPair[][]? Pages)? _dialoguePreview;
    private Harmony? _harmony;
    private RawContentProvider? _contentProvider;
    private ItemNameResolver? _nameResolver;
    private BilingualFontManager? _fontManager;
    private UntranslatedStardewApi? _api;
    private readonly System.Collections.Concurrent.ConcurrentDictionary<string, (RawContentProvider Provider, ItemNameResolver Resolver)> _languageResolvers = new(StringComparer.OrdinalIgnoreCase);

    public override void Entry(IModHelper helper)
    {
        Instance = this;

        // Initialize translation helper generated by ModTranslationClassBuilder
        I18n.Init(helper.Translation);

        // Read configuration (handle null or empty fields safely)
        Config = helper.ReadConfig<ModConfig>();
        if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
        {
            Config.SecondaryLanguage = "default";
        }

        // DirectoryPath is concrete SMAPI metadata, not part of IModInfo; fail closed if unavailable.
        SourceRegistry.ModDirectoryResolver = sourceId =>
        {
            try
            {
                IModInfo? info = Helper.ModRegistry.Get(sourceId);
                return info?.GetType().GetProperty("DirectoryPath")?.GetValue(info) as string;
            }
            catch { return null; }
        };
        // Initialize language source registry and bundled compatibility descriptor
        SourceRegistry.OnChanged += () =>
        {
            _nameResolver?.Invalidate();
            _fontManager?.Invalidate();
            ClearLanguageResolvers();
        };

        // Initialize stable API referencing resolver dynamically
        _api = new UntranslatedStardewApi(() => _nameResolver, () => Config, GetResolverForLanguage, () => SourceRegistry);

        // Build initial resolver with lazy service provider
        InitializeResolver();

        // Apply Harmony patches
        try
        {
            ValidatePatchSignatures();
            _harmony = new Harmony(ModManifest.UniqueID);
            _harmony.PatchAll(typeof(ModEntry).Assembly);
        }
        catch (Exception ex)
        {
            Monitor.Log(I18n.Log_PatchFailed(ex.Message), LogLevel.Warn);
        }

        // Register event handlers
        helper.Events.GameLoop.GameLaunched += OnGameLaunched;
        helper.Events.Content.LocaleChanged += OnLocaleChanged;
        helper.Events.Content.AssetsInvalidated += OnAssetsInvalidated;
        helper.Events.Content.AssetRequested += OnAssetRequested;

        // Register diagnostic console command
        helper.ConsoleCommands.Add(
            "untranslated_audit",
            "Audits active item registry coverage for bilingual names.\nUsage: untranslated_audit [summary|details]",
            OnAuditCommand
        );

        helper.ConsoleCommands.Add(
            "untranslated_dialogue_test",
            "Opens a bilingual dialogue sample without changing configuration. Usage: untranslated_dialogue_test [above|below] [wrap|pairs|authored|gender|weekly|key <NPC> <key>]",
            OnDialoguePreviewCommand
        );

        helper.ConsoleCommands.Add(
            "untranslated_dialogue_check",
            "Runs dialogue rules without opening a menu. Usage: untranslated_dialogue_check [branch|pairs|fallback|layout|all]",
            OnDialogueCheckCommand
        );

        string effectiveLang = _contentProvider?.EffectiveLanguage ?? Config.SecondaryLanguage;
        Monitor.Log(I18n.Log_ModLoaded(effectiveLang), LogLevel.Info);
    }

    private void OnDialogueCheckCommand(string command, string[] args)
    {
        string group = args.FirstOrDefault()?.ToLowerInvariant() ?? "all";
        var checks = args.Length <= 1 ? DialogueChecks.Run(group) : null;
        if (checks == null)
        {
            Monitor.Log("Usage: untranslated_dialogue_check [branch|pairs|fallback|layout|all]", LogLevel.Info);
            return;
        }

        foreach (var check in checks)
            Monitor.Log($"[{(check.Passed ? "PASS" : "FAIL")}] {check.Name}", check.Passed ? LogLevel.Info : LogLevel.Error);

        int passed = checks.Count(check => check.Passed);
        Monitor.Log($"Dialogue checks ({group}): {passed}/{checks.Length} passed.",
            passed == checks.Length ? LogLevel.Info : LogLevel.Error);
    }

    private void OnDialoguePreviewCommand(string command, string[] args)
    {
        int offset = args.FirstOrDefault() is "above" or "below" ? 1 : 0;
        string? sample = args.ElementAtOrDefault(offset);
        bool fromKey = sample == "key" && args.Length == offset + 3;
        bool builtInSample = args.Length - offset <= 1 && sample is null or "wrap" or "pairs" or "authored" or "gender" or "weekly";
        if (!fromKey && !builtInSample)
        {
            Monitor.Log("Usage: untranslated_dialogue_test [above|below] [wrap|pairs|authored|gender|weekly|key <NPC> <key>]", LogLevel.Info);
            return;
        }

        if (!Context.CanPlayerMove || Game1.eventUp || Game1.currentMinigame != null
            || Game1.afterDialogues != null || Game1.currentObjectDialogue.Count > 0)
        {
            Monitor.Log("Load a save and close any menus or dialogue before running the preview.", LogLevel.Info);
            return;
        }

        if (Helper.ModRegistry.IsLoaded("Mangupix.DialogueDisplayFrameworkContinued"))
        {
            Monitor.Log("The preview needs vanilla dialogue rendering.", LogLevel.Warn);
            return;
        }

        string npcName = fromKey ? args[offset + 1] : "Evelyn";
        string key = fromKey ? args[offset + 2] : "Mon";
        NPC? npc = Game1.getCharacterFromName(npcName);
        if (npc?.Portrait is not { } portrait)
        {
            Monitor.Log($"NPC '{npcName}' or their portrait is unavailable in this save.", LogLevel.Warn);
            return;
        }

        string asset = $"Characters/Dialogue/{npc.Name}";
        string? primary;
        try
        {
            var lines = Game1.content.Load<Dictionary<string, string>>(asset);
            lines.TryGetValue(key, out primary);
        }
        catch (Microsoft.Xna.Framework.Content.ContentLoadException)
        {
            primary = null;
        }

        if (primary == null || !DialogueTranslation.IsSafePreview(primary))
        {
            Monitor.Log($"'{asset}:{key}' was not found or uses unsupported dialogue commands.", LogLevel.Warn);
            return;
        }

        string plainSample = "";
        if (sample is "wrap" or "pairs" or "gender" or "weekly"
            && !DialogueTranslation.TryGetPlainText(primary, out plainSample))
        {
            Monitor.Log("This preview needs the plain Evelyn Monday line as its sample.", LogLevel.Warn);
            return;
        }

        // Closing the preview must not consume the real NPC's queued dialogue.
        var speaker = new NPC { Name = npc.Name, displayName = npc.displayName, Portrait = portrait, EventActor = true };
        var box = new DialogueBox(new Dialogue(speaker, $"{asset}:{key}", primary));
        string visibleText = box.getCurrentString()[GetDialogueSpeakerPrefix(box.characterDialogue).Length..];
        string? secondary = GetSecondaryDialogueText(box.characterDialogue, visibleText);
        var font = _fontManager?.GetSecondaryFont(Game1.dialogueFont);
        if (secondary == null || font == null || !secondary.All(font.Characters.Contains))
        {
            Monitor.Log("No usable secondary line for this sample. Set a different secondary language with a dialogue translation and font.", LogLevel.Warn);
            return;
        }

        DialogueTextPair[][]? pages = fromKey || sample == "authored"
            ? null
            : new[] { new[] { new DialogueTextPair(visibleText, secondary) } };
        if (sample is "wrap" or "pairs")
        {
            string longPrimary = string.Join(" ", Enumerable.Repeat(plainSample, 3));
            string longVisible = string.Join(" ", Enumerable.Repeat(visibleText, 3));
            string longSecondary = string.Join(" ", Enumerable.Repeat(secondary, 3));
            var shortPair = new DialogueTextPair(visibleText, secondary);
            var longPair = new DialogueTextPair(longVisible, longSecondary);
            bool samePage = sample == "pairs";
            string authored = samePage ? $"{plainSample} {longPrimary}" : $"{longPrimary}#$b#{primary}";
            box = new DialogueBox(new Dialogue(speaker, $"{asset}:{key}", authored));
            pages = samePage
                ? new[] { new[] { shortPair, longPair } }
                : new[] { new[] { longPair }, new[] { shortPair } };
        }

        if (sample is "gender" or "weekly")
        {
            string authored;
            string translated;
            uint daysPlayed = Game1.stats.DaysPlayed;
            if (sample == "weekly")
            {
                authored = $"{plainSample}||{plainSample} {plainSample}";
                translated = $"{secondary}||{secondary} {secondary}";
                int selected = DialogueTranslation.GetWeeklyVariantIndex(daysPlayed, 2) + 1;
                Monitor.Log($"Weekly preview: DaysPlayed={daysPlayed}, variant {selected}/2 (short, then long).", LogLevel.Info);
            }
            else
            {
                authored = "${" + plainSample + "^" + plainSample + " " + plainSample + "}$#$b#"
                    + plainSample + " " + plainSample + "^" + plainSample + "#$b#"
                    + "${^}$" + plainSample + "${^ " + plainSample + "}$";
                translated = "${" + secondary + "^" + secondary + " " + secondary + "}$#$b#"
                    + secondary + " " + secondary + "^" + secondary + "#$b#"
                    + "${^}$" + secondary + "${^ " + secondary + "}$";
            }

            string[] weeks = authored.Split("||");
            string[] sourcePages = weeks[DialogueTranslation.GetWeeklyVariantIndex(daysPlayed, weeks.Length)].Split("#$b#");
            Gender gender = Game1.player.Gender;
            string playerName = Utility.FilterUserName(Game1.player.Name);
            pages = new DialogueTextPair[sourcePages.Length][];
            for (int i = 0; i < sourcePages.Length; i++)
            {
                DialogueTranslation.TryResolveSegment(sourcePages[i], gender, out string resolved);
                string shown = resolved.Replace("@", playerName);
                string? paired = DialogueTranslation.GetSecondaryLine(authored, translated, i, shown, playerName, gender, daysPlayed);
                if (paired == null)
                {
                    Monitor.Log($"This language pair cannot use the {sample} preview sample.", LogLevel.Warn);
                    return;
                }

                pages[i] = new[] { new DialogueTextPair(shown, paired) };
            }
            box = new DialogueBox(new Dialogue(speaker, $"{asset}:{key}", authored));
        }

        bool secondaryFirst = offset == 0 ? Config.SecondaryFirst : args[0] == "above";
        _dialoguePreview = (new WeakReference<DialogueBox>(box), secondaryFirst, pages);
        Game1.activeClickableMenu = box;
        Game1.dialogueUp = true;
        Game1.player.Halt();
        Game1.player.CanMove = false;
    }

    internal (bool SecondaryFirst, DialogueTextPair[][]? Pages)? GetDialoguePreview(DialogueBox box)
        => _dialoguePreview is { } preview && preview.Box.TryGetTarget(out DialogueBox? target)
            && ReferenceEquals(target, box)
            ? (preview.SecondaryFirst, preview.Pages)
            : null;

    internal static string GetDialogueSpeakerPrefix(Dialogue dialogue)
        => !Game1.options.showPortraits && dialogue.speaker is { } speaker ? speaker.getName() + ": " : "";

    internal DialogueTextPair[]? GetDialoguePairs(Dialogue dialogue, string visibleText)
    {
        string? secondary = GetSecondaryDialogueText(dialogue, visibleText);
        if (secondary == null)
            return null;

        try
        {
            var entries = Game1.content.Load<Dictionary<string, string[][]>>(DialoguePairsAsset);
            string key = dialogue.TranslationKey.Replace('\\', '/');
            if (entries.TryGetValue(key, out string[][]? variants)
                && DialogueTranslation.MatchBlocks(visibleText, secondary, variants,
                    Utility.FilterUserName(Game1.player.Name)) is { } pairs)
                return pairs;
        }
        catch (Microsoft.Xna.Framework.Content.ContentLoadException)
        {
            // A broken pairing asset should not suppress an otherwise usable translation.
        }

        return new[] { new DialogueTextPair(visibleText, secondary) };
    }

    internal string? GetSecondaryDialogueText(Dialogue? dialogue, string visibleText)
    {
        if (dialogue?.TranslationKey is not { } translationKey || _contentProvider == null)
            return null;

        int separator = translationKey.IndexOf(':');
        if (separator < 0)
            return null;

        string asset = translationKey[..separator].Replace('\\', '/');
        string key = translationKey[(separator + 1)..];
        const string dialogueRoot = "Characters/Dialogue/";
        if (!asset.StartsWith(dialogueRoot, StringComparison.OrdinalIgnoreCase))
            return null;

        string file = asset[dialogueRoot.Length..];
        if (string.IsNullOrWhiteSpace(file) || file is "." or ".."
            || file.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0
            || !_contentProvider.TryGetDialogueString(asset, key, out string? secondary))
            return null;

        try
        {
            // Read the authored value so localization preprocessing cannot hide unsupported syntax.
            var primaryStrings = Game1.content.Load<System.Collections.Generic.Dictionary<string, string>>(asset);
            if (!primaryStrings.TryGetValue(key, out string? primary) || primary == null)
                return null;

            return DialogueTranslation.GetSecondaryLine(primary, secondary!, dialogue.currentDialogueIndex,
                visibleText, Utility.FilterUserName(Game1.player.Name), Game1.player.Gender, Game1.stats.DaysPlayed);
        }
        catch (Microsoft.Xna.Framework.Content.ContentLoadException)
        {
            return null;
        }
    }

    public override object? GetApi()
    {
        return _api;
    }

    /// <summary>
    /// Formats the tooltip title using the active resolver and configuration.
    /// Called safely from TooltipPatch prefix.
    /// </summary>
    internal void FormatTooltipTitle(ref string hoverTitle, Item hoveredItem)
    {
        if (!Config.ShowSecondaryInTooltip || _nameResolver == null)
            return;

        string primaryName = hoveredItem.DisplayName;
        string? secondaryName = _nameResolver.GetSecondaryName(hoveredItem);

        hoverTitle = TooltipFormatter.FormatTitle(hoverTitle, primaryName, secondaryName, Config.SecondaryFirst);
    }

    private void OnGameLaunched(object? sender, GameLaunchedEventArgs e)
    {
        // Re-initialize to ensure ServiceProvider is bound once game content pipeline is live
        InitializeResolver();
        ReloadCpTranslations();
        ReloadLanguageSources();
        DiscoverAdditionalLanguages();

        RegisterGenericModConfigMenu();

        // Dynamically integrate with CJB Item Spawner if present
        if (_harmony != null)
        {
            Patches.CjbItemSpawnerIntegration.TryApply(_harmony, Helper.ModRegistry, Monitor);
        }
    }

    private void OnLocaleChanged(object? sender, LocaleChangedEventArgs e)
    {
        _nameResolver?.Invalidate();
        _fontManager?.Invalidate();
    }

    private void OnAssetRequested(object? sender, AssetRequestedEventArgs e)
    {
        if (e.NameWithoutLocale.IsEquivalentTo("Mods/GiaHung.UntranslatedStardew/Names"))
        {
            e.LoadFrom(() => new System.Collections.Generic.Dictionary<string, string>(StringComparer.OrdinalIgnoreCase), AssetLoadPriority.Exclusive);
        }
        else if (e.NameWithoutLocale.IsEquivalentTo("Mods/GiaHung.UntranslatedStardew/LanguageSources"))
        {
            e.LoadFrom(() => new System.Collections.Generic.Dictionary<string, LanguageSourceDescriptor>(StringComparer.OrdinalIgnoreCase), AssetLoadPriority.Exclusive);
        }
        else if (e.NameWithoutLocale.IsEquivalentTo(DialoguePairsAsset))
        {
            e.LoadFrom(() => new Dictionary<string, string[][]>(StringComparer.OrdinalIgnoreCase)
            {
                ["Characters/Dialogue/Evelyn:Mon"] = new[]
                {
                    new[] { "Oh my!", "What a lovely day." },
                    new[] { "Ôi chao!", "Một ngày đẹp trời." }
                }
            }, AssetLoadPriority.Exclusive);
        }
    }

    private void OnAssetsInvalidated(object? sender, AssetsInvalidatedEventArgs e)
    {
        if (e.NamesWithoutLocale.Any(name => name.IsEquivalentTo("Mods/GiaHung.UntranslatedStardew/Names")))
        {
            ReloadCpTranslations();
            _nameResolver?.Invalidate();
            _fontManager?.Invalidate();
            ClearLanguageResolvers();
            // A CP reload can invalidate both Names and LanguageSources in the same batch.
        }

        if (e.NamesWithoutLocale.Any(name => name.IsEquivalentTo("Mods/GiaHung.UntranslatedStardew/LanguageSources") || name.IsEquivalentTo("Data/AdditionalLanguages")))
        {
            ReloadLanguageSources();
            DiscoverAdditionalLanguages();
            _nameResolver?.Invalidate();
            _fontManager?.Invalidate();
            ClearLanguageResolvers();
            return;
        }

        if (e.NamesWithoutLocale.Any(name =>
            name.IsEquivalentTo("Strings/Objects") ||
            name.IsEquivalentTo("Strings/Weapons") ||
            name.IsEquivalentTo("Strings/Tools") ||
            name.IsEquivalentTo("Strings/BigCraftables") ||
            name.IsEquivalentTo("Strings/1_6_Strings") ||
            name.IsEquivalentTo("Strings/UI") ||
            name.IsEquivalentTo("Strings/StringsFromCSFiles") ||
            name.IsEquivalentTo("Strings/Locations") ||
            name.IsEquivalentTo("Strings/Furniture") ||
            name.IsEquivalentTo("Strings/Pants") ||
            name.IsEquivalentTo("Strings/Shirts") ||
            name.IsEquivalentTo("Data/Objects") ||
            name.IsEquivalentTo("Data/Weapons") ||
            name.IsEquivalentTo("Data/Tools") ||
            name.IsEquivalentTo("Data/BigCraftables") ||
            name.IsEquivalentTo("Data/Boots") ||
            name.IsEquivalentTo("Data/hats") ||
            name.IsEquivalentTo("Data/Furniture") ||
            name.IsEquivalentTo("Data/Trinkets") ||
            name.IsEquivalentTo("Data/mail") ||
            name.IsEquivalentTo("Data/SecretNotes") ||
            name.IsEquivalentTo("Data/Powers") ||
            name.IsEquivalentTo("Data/Achievements") ||
            name.IsEquivalentTo("Data/Pants") ||
            name.IsEquivalentTo("Data/Shirts") ||
            name.IsEquivalentTo("Data/Mannequins") ||
            name.StartsWith("Fonts")))
        {
            _nameResolver?.Invalidate();
            _fontManager?.Invalidate();
            ClearLanguageResolvers();
        }
    }

    private void ReloadCpTranslations()
    {
        if (Game1.content != null && _nameResolver != null)
        {
            try
            {
                var cpDict = Game1.content.Load<System.Collections.Generic.Dictionary<string, string>>("Mods/GiaHung.UntranslatedStardew/Names");
                if (cpDict != null)
                {
                    _nameResolver.ExternalRegistry.LoadFromContentPackDictionary(cpDict);
                }
            }
            catch (Exception)
            {
                // Asset might not be ready yet
            }
        }
    }

    private void ReloadLanguageSources()
    {
        if (Game1.content != null)
        {
            try
            {
                var sourcesDict = Game1.content.Load<System.Collections.Generic.Dictionary<string, LanguageSourceDescriptor>>("Mods/GiaHung.UntranslatedStardew/LanguageSources");
                if (sourcesDict != null)
                {
                    SourceRegistry.LoadFromAssetDictionary(sourcesDict);
                }
            }
            catch (Exception)
            {
                // Asset might not be ready yet
            }
        }
    }

    private void DiscoverAdditionalLanguages()
    {
        if (Game1.content == null) return;
        try
        {
            var descriptors = new System.Collections.Generic.List<LanguageSourceDescriptor>();
            var packs = Helper.ModRegistry.GetAll()
                .Where(info => string.Equals(info.Manifest.ContentPackFor?.UniqueID, "Pathoschild.ContentPatcher", StringComparison.OrdinalIgnoreCase))
                .Select(info => (Id: info.Manifest.UniqueID, Directory: SourceRegistry.ModDirectoryResolver?.Invoke(info.Manifest.UniqueID)))
                .Where(pack => pack.Directory != null)
                .Select(pack => (pack.Id, pack.Directory!))
                .ToArray();
            foreach (var language in DataLoader.AdditionalLanguages(Game1.content))
            {
                if (language == null || string.IsNullOrWhiteSpace(language.LanguageCode)) continue;
                var fields = language.CustomFields ?? new System.Collections.Generic.Dictionary<string, string>();
                fields.TryGetValue("UntranslatedStardew.SourceModId", out string? owner);
                bool detected = string.IsNullOrWhiteSpace(owner);
                var reader = new CustomLanguagePackReader(language.LanguageCode, Game1.content.ServiceProvider,
                    message => Monitor.Log(message, LogLevel.Trace));
                var strings = reader.Read(packs);
                fields.TryGetValue("UntranslatedStardew.ContentRoot", out string? root);
                fields.TryGetValue("UntranslatedStardew.AssetPattern", out string? pattern);
                fields.TryGetValue("UntranslatedStardew.SmallFont", out string? small);
                fields.TryGetValue("UntranslatedStardew.DialogueFont", out string? dialogue);
                descriptors.Add(new LanguageSourceDescriptor
                {
                    SourceModId = detected ? ModManifest.UniqueID : owner!,
                    LanguageCode = language.LanguageCode,
                    ContentRoot = root,
                    AssetPattern = pattern,
                    SmallFont = small,
                    DialogueFont = dialogue,
                    CustomFields = fields,
                    Strings = strings,
                    SpriteFontAssets = reader.SpriteFontAssets,
                    BitmapFontAsset = language.UseLatinFont ? null : language.FontFile,
                    BitmapFontZoom = language.FontPixelZoom,
                    UseGameLatinFont = language.UseLatinFont,
                    GameSmallFontLineSpacing = language.SmallFontLineSpacing,
                    DetectedFromGame = detected
                });
            }
            SourceRegistry.LoadFromAdditionalLanguages(descriptors);
        }
        catch (Exception ex) { Monitor.Log($"Could not reload custom language descriptors: {ex.Message}", LogLevel.Trace); }
    }

    private void OnAuditCommand(string command, string[] args)
    {
        if (_nameResolver == null)
        {
            Monitor.Log("Untranslated Stardew: Resolver is not initialized.", LogLevel.Warn);
            return;
        }

        bool showDetails = args.Length > 0 && args[0].Equals("details", StringComparison.OrdinalIgnoreCase);
        string secondaryLang = _nameResolver.EffectiveLanguage;

        Monitor.Log($"=== Untranslated Stardew Coverage Audit (Secondary: {secondaryLang}) ===", LogLevel.Info);

        bool sourceConfigured = _contentProvider != null && _contentProvider.EffectiveLanguage.Equals(LanguageHelper.CanonicalizeLanguageCode(Config.SecondaryLanguage), StringComparison.OrdinalIgnoreCase);
        bool smallFontAvailable = Game1.smallFont != null && _fontManager?.GetSecondaryFont(Game1.smallFont) != null;
        bool dialogueFontAvailable = Game1.dialogueFont != null && _fontManager?.GetSecondaryFont(Game1.dialogueFont) != null;

        Monitor.Log($"Language Source: {(sourceConfigured ? "Registered & Active" : $"Unregistered or Missing for '{Config.SecondaryLanguage}' (effective: {_contentProvider?.EffectiveLanguage})")}", LogLevel.Info);
        Monitor.Log($"Secondary Fonts: SmallFont: {(smallFontAvailable ? "Available" : "Unavailable (primary fallback)")} | DialogueFont: {(dialogueFontAvailable ? "Available" : "Unavailable (primary fallback)")}", LogLevel.Info);

        int totalItems = 0;
        int totalResolved = 0;
        int totalSameName = 0;
        int totalMissing = 0;

        var categoryStats = new System.Collections.Generic.List<(string TypeId, int Total, int Resolved, int SameName, int Missing)>();
        var missingDetails = new System.Collections.Generic.List<(string QualifiedId, string PrimaryName)>();

        foreach (StardewValley.ItemTypeDefinitions.IItemDataDefinition itemType in ItemRegistry.ItemTypes)
        {
            int typeTotal = 0;
            int typeResolved = 0;
            int typeSameName = 0;
            int typeMissing = 0;

            foreach (string itemId in itemType.GetAllIds())
            {
                typeTotal++;
                totalItems++;

                string qualifiedId = itemType.Identifier + itemId;
                StardewValley.ItemTypeDefinitions.ParsedItemData? data = itemType.GetData(itemId);
                string primaryName = data?.DisplayName ?? itemId;
                string? secondaryName = _nameResolver.GetSecondaryNameById(qualifiedId);

                if (string.IsNullOrEmpty(secondaryName))
                {
                    typeMissing++;
                    totalMissing++;
                    if (showDetails && missingDetails.Count < 50)
                    {
                        missingDetails.Add((qualifiedId, primaryName));
                    }
                }
                else if (string.Equals(primaryName, secondaryName, StringComparison.OrdinalIgnoreCase))
                {
                    typeSameName++;
                    totalSameName++;
                }
                else
                {
                    typeResolved++;
                    totalResolved++;
                }
            }

            categoryStats.Add((itemType.Identifier, typeTotal, typeResolved, typeSameName, typeMissing));
        }

        Monitor.Log(string.Format("{0,-8} | {1,7} | {2,9} | {3,9} | {4,7}", "Type", "Total", "Bilingual", "Same-Name", "Missing"), LogLevel.Info);
        Monitor.Log(new string('-', 52), LogLevel.Info);

        foreach (var stat in categoryStats)
        {
            Monitor.Log(string.Format("{0,-8} | {1,7} | {2,9} | {3,9} | {4,7}", stat.TypeId, stat.Total, stat.Resolved, stat.SameName, stat.Missing), LogLevel.Info);
        }

        Monitor.Log(new string('-', 52), LogLevel.Info);
        Monitor.Log($"Summary: {totalItems} total items | {totalResolved} distinct bilingual | {totalSameName} same-name suppressed | {totalMissing} missing data.", LogLevel.Info);

        if (missingDetails.Count > 0)
        {
            Monitor.Log($"First {missingDetails.Count} missing items:", LogLevel.Info);
            foreach (var (qId, pName) in missingDetails)
            {
                Monitor.Log($"  - {qId}: {pName}", LogLevel.Info);
            }
        }
    }

    private void RegisterGenericModConfigMenu()
    {
        var gmcm = Helper.ModRegistry.GetApi<IGenericModConfigMenuApi>("spacechase0.GenericModConfigMenu");
        if (gmcm == null)
            return;

        gmcm.Register(
            mod: ModManifest,
            reset: () =>
            {
                Config = new ModConfig();
                InitializeResolver();
            },
            titleScreenOnly: false,
            save: () =>
            {
                if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
                {
                    Config.SecondaryLanguage = "default";
                }
                Helper.WriteConfig(Config);
                InitializeResolver();
            }
        );

        gmcm.AddTextOption(
            mod: ModManifest,
            getValue: () => Config.SecondaryLanguage,
            setValue: value => Config.SecondaryLanguage = value,
            name: I18n.Config_SecondaryLanguage_Name,
            tooltip: I18n.Config_SecondaryLanguage_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
