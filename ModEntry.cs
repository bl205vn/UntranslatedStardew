using System;
using System.IO;
using System.Linq;
using HarmonyLib;
using StardewModdingAPI;
using StardewModdingAPI.Events;
using StardewValley;
using UntranslatedStardew.Core;

namespace UntranslatedStardew;

/// <summary>
/// The main entry point for Untranslated Stardew mod.
/// Intercepts item tooltips to show bilingual item names and provides search APIs.
/// </summary>
public sealed class ModEntry : Mod
{
    internal static ModEntry? Instance { get; private set; }

    public ModConfig Config { get; private set; } = null!;
    public ItemNameResolver? Resolver => _nameResolver;

    private Harmony? _harmony;
    private RawContentProvider? _contentProvider;
    private ItemNameResolver? _nameResolver;
    private UntranslatedStardewApi? _api;

    public override void Entry(IModHelper helper)
    {
        Instance = this;

        // Initialize translation helper generated by ModTranslationClassBuilder
        I18n.Init(helper.Translation);

        // Read configuration (handle null or empty fields safely)
        Config = helper.ReadConfig<ModConfig>();
        if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
        {
            Config.SecondaryLanguage = "default";
        }

        // Initialize stable API referencing resolver dynamically
        _api = new UntranslatedStardewApi(() => _nameResolver, () => Config);

        // Build initial resolver with lazy service provider
        InitializeResolver();

        // Apply Harmony patches
        try
        {
            ValidatePatchSignatures();
            _harmony = new Harmony(ModManifest.UniqueID);
            _harmony.PatchAll(typeof(ModEntry).Assembly);
        }
        catch (Exception ex)
        {
            Monitor.Log(I18n.Log_PatchFailed(ex.Message), LogLevel.Warn);
        }

        // Register event handlers
        helper.Events.GameLoop.GameLaunched += OnGameLaunched;
        helper.Events.Content.LocaleChanged += OnLocaleChanged;
        helper.Events.Content.AssetsInvalidated += OnAssetsInvalidated;

        // Register diagnostic console command
        helper.ConsoleCommands.Add(
            "untranslated_audit",
            "Audits active item registry coverage for bilingual names.\nUsage: untranslated_audit [summary|details]",
            OnAuditCommand
        );

        string effectiveLang = _contentProvider?.EffectiveLanguage ?? Config.SecondaryLanguage;
        Monitor.Log(I18n.Log_ModLoaded(effectiveLang), LogLevel.Info);
    }

    public override object? GetApi()
    {
        return _api;
    }

    /// <summary>
    /// Formats the tooltip title using the active resolver and configuration.
    /// Called safely from TooltipPatch prefix.
    /// </summary>
    internal void FormatTooltipTitle(ref string hoverTitle, Item hoveredItem)
    {
        if (!Config.ShowSecondaryInTooltip || _nameResolver == null)
            return;

        string primaryName = hoveredItem.DisplayName;
        string? secondaryName = _nameResolver.GetSecondaryName(hoveredItem);

        hoverTitle = TooltipFormatter.FormatTitle(hoverTitle, primaryName, secondaryName, Config.SecondaryFirst);
    }

    private void OnGameLaunched(object? sender, GameLaunchedEventArgs e)
    {
        // Re-initialize to ensure ServiceProvider is bound once game content pipeline is live
        InitializeResolver();

        RegisterGenericModConfigMenu();

        // Dynamically integrate with CJB Item Spawner if present
        if (_harmony != null)
        {
            Patches.CjbItemSpawnerIntegration.TryApply(_harmony, Helper.ModRegistry, Monitor);
        }
    }

    private void OnLocaleChanged(object? sender, LocaleChangedEventArgs e)
    {
        _nameResolver?.Invalidate();
    }

    private void OnAssetsInvalidated(object? sender, AssetsInvalidatedEventArgs e)
    {
        if (e.NamesWithoutLocale.Any(name =>
            name.IsEquivalentTo("Strings/Objects") ||
            name.IsEquivalentTo("Strings/Weapons") ||
            name.IsEquivalentTo("Strings/Tools") ||
            name.IsEquivalentTo("Strings/BigCraftables") ||
            name.IsEquivalentTo("Strings/1_6_Strings") ||
            name.IsEquivalentTo("Strings/UI") ||
            name.IsEquivalentTo("Strings/StringsFromCSFiles") ||
            name.IsEquivalentTo("Strings/Furniture") ||
            name.IsEquivalentTo("Strings/Pants") ||
            name.IsEquivalentTo("Strings/Shirts") ||
            name.IsEquivalentTo("Data/Objects") ||
            name.IsEquivalentTo("Data/Weapons") ||
            name.IsEquivalentTo("Data/Tools") ||
            name.IsEquivalentTo("Data/BigCraftables") ||
            name.IsEquivalentTo("Data/Boots") ||
            name.IsEquivalentTo("Data/hats") ||
            name.IsEquivalentTo("Data/Furniture") ||
            name.IsEquivalentTo("Data/Trinkets") ||
            name.IsEquivalentTo("Data/Powers") ||
            name.IsEquivalentTo("Data/Achievements") ||
            name.IsEquivalentTo("Data/Pants") ||
            name.IsEquivalentTo("Data/Shirts") ||
            name.IsEquivalentTo("Data/Mannequins")))
        {
            _nameResolver?.Invalidate();
        }
    }

    private void OnAuditCommand(string command, string[] args)
    {
        if (_nameResolver == null)
        {
            Monitor.Log("Untranslated Stardew: Resolver is not initialized.", LogLevel.Warn);
            return;
        }

        bool showDetails = args.Length > 0 && args[0].Equals("details", StringComparison.OrdinalIgnoreCase);
        string secondaryLang = _nameResolver.EffectiveLanguage;

        Monitor.Log($"=== Untranslated Stardew Coverage Audit (Secondary: {secondaryLang}) ===", LogLevel.Info);

        int totalItems = 0;
        int totalResolved = 0;
        int totalSameName = 0;
        int totalMissing = 0;

        var categoryStats = new System.Collections.Generic.List<(string TypeId, int Total, int Resolved, int SameName, int Missing)>();
        var missingDetails = new System.Collections.Generic.List<(string QualifiedId, string PrimaryName)>();

        foreach (StardewValley.ItemTypeDefinitions.IItemDataDefinition itemType in ItemRegistry.ItemTypes)
        {
            int typeTotal = 0;
            int typeResolved = 0;
            int typeSameName = 0;
            int typeMissing = 0;

            foreach (string itemId in itemType.GetAllIds())
            {
                typeTotal++;
                totalItems++;

                string qualifiedId = itemType.Identifier + itemId;
                StardewValley.ItemTypeDefinitions.ParsedItemData? data = itemType.GetData(itemId);
                string primaryName = data?.DisplayName ?? itemId;
                string? secondaryName = _nameResolver.GetSecondaryNameById(qualifiedId);

                if (string.IsNullOrEmpty(secondaryName))
                {
                    typeMissing++;
                    totalMissing++;
                    if (showDetails && missingDetails.Count < 50)
                    {
                        missingDetails.Add((qualifiedId, primaryName));
                    }
                }
                else if (string.Equals(primaryName, secondaryName, StringComparison.OrdinalIgnoreCase))
                {
                    typeSameName++;
                    totalSameName++;
                }
                else
                {
                    typeResolved++;
                    totalResolved++;
                }
            }

            categoryStats.Add((itemType.Identifier, typeTotal, typeResolved, typeSameName, typeMissing));
        }

        Monitor.Log(string.Format("{0,-8} | {1,7} | {2,9} | {3,9} | {4,7}", "Type", "Total", "Bilingual", "Same-Name", "Missing"), LogLevel.Info);
        Monitor.Log(new string('-', 52), LogLevel.Info);

        foreach (var stat in categoryStats)
        {
            Monitor.Log(string.Format("{0,-8} | {1,7} | {2,9} | {3,9} | {4,7}", stat.TypeId, stat.Total, stat.Resolved, stat.SameName, stat.Missing), LogLevel.Info);
        }

        Monitor.Log(new string('-', 52), LogLevel.Info);
        Monitor.Log($"Summary: {totalItems} total items | {totalResolved} distinct bilingual | {totalSameName} same-name suppressed | {totalMissing} missing data.", LogLevel.Info);

        if (missingDetails.Count > 0)
        {
            Monitor.Log($"First {missingDetails.Count} missing items:", LogLevel.Info);
            foreach (var (qId, pName) in missingDetails)
            {
                Monitor.Log($"  - {qId}: {pName}", LogLevel.Info);
            }
        }
    }

    private void RegisterGenericModConfigMenu()
    {
        var gmcm = Helper.ModRegistry.GetApi<IGenericModConfigMenuApi>("spacechase0.GenericModConfigMenu");
        if (gmcm == null)
            return;

        gmcm.Register(
            mod: ModManifest,
            reset: () =>
            {
                Config = new ModConfig();
                InitializeResolver();
            },
            save: () =>
            {
                if (string.IsNullOrWhiteSpace(Config.SecondaryLanguage))
                {
                    Config.SecondaryLanguage = "default";
                }
                Helper.WriteConfig(Config);
                InitializeResolver();
            }
        );

        gmcm.AddTextOption(
            mod: ModManifest,
            getValue: () => Config.SecondaryLanguage,
            setValue: value => Config.SecondaryLanguage = value,
            name: I18n.Config_SecondaryLanguage_Name,
            tooltip: I18n.Config_SecondaryLanguage_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.ShowSecondaryInTooltip,
            setValue: value => Config.ShowSecondaryInTooltip = value,
            name: I18n.Config_ShowSecondary_Name,
            tooltip: I18n.Config_ShowSecondary_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.SecondaryFirst,
            setValue: value => Config.SecondaryFirst = value,
            name: I18n.Config_SecondaryFirst_Name,
            tooltip: I18n.Config_SecondaryFirst_Description
        );

        gmcm.AddBoolOption(
            mod: ModManifest,
            getValue: () => Config.DiacriticInsensitiveSearch,
            setValue: value => Config.DiacriticInsensitiveSearch = value,
            name: I18n.Config_DiacriticInsensitive_Name,
            tooltip: I18n.Config_DiacriticInsensitive_Description
        );
    }

    private void InitializeResolver()
    {
        _contentProvider?.Dispose();

        string gameContentRoot = Path.Combine(Constants.GamePath, "Content");
        string? modContentRoot = DiscoverVietnamesePackContentPath();

        _contentProvider = new RawContentProvider(
            () => Game1.content?.ServiceProvider,
            gameContentRoot,
            Config.SecondaryLanguage,
            modContentRoot,
            (requested, fallback) => Monitor.Log(I18n.Log_SecondaryFallback(requested, fallback), LogLevel.Warn)
        );

        _nameResolver = new ItemNameResolver(_contentProvider);
    }

    private string? DiscoverVietnamesePackContentPath()
    {
        // 1. Try public SMAPI ModRegistry for Kou.ViethoaSV
        IModInfo? modInfo = Helper.ModRegistry.Get("Kou.ViethoaSV");
        if (modInfo != null)
        {
            string? dir = modInfo.GetType().GetProperty("DirectoryPath")?.GetValue(modInfo) as string;
            if (!string.IsNullOrEmpty(dir))
            {
                string targetContent = Path.Combine(dir, "assets", "Content");
                if (Directory.Exists(targetContent))
                    return targetContent;
            }
        }

        // 2. Fallback to standard mod folder name
        string standardFolder = Path.Combine(Constants.GamePath, "Mods", "Stardew Valley Viethoa", "assets", "Content");
        if (Directory.Exists(standardFolder))
            return standardFolder;

        return null;
    }

    private void ValidatePatchSignatures()
    {
        var targets = new (Type Type, string Method, Type[]? ParamTypes)[]
        {
            (typeof(StardewValley.Menus.IClickableMenu), nameof(StardewValley.Menus.IClickableMenu.drawToolTip), null),
            (typeof(StardewValley.Menus.SkillsPage), nameof(StardewValley.Menus.SkillsPage.performHoverAction), null),
            (typeof(StardewValley.Menus.LevelUpMenu), nameof(StardewValley.Menus.LevelUpMenu.draw), new[] { typeof(Microsoft.Xna.Framework.Graphics.SpriteBatch) }),
            (typeof(StardewValley.Menus.PowersTab), nameof(StardewValley.Menus.PowersTab.performHoverAction), null),
            (typeof(StardewValley.Menus.CollectionsPage), nameof(StardewValley.Menus.CollectionsPage.createDescription), new[] { typeof(string) })
        };

        foreach (var (type, method, paramTypes) in targets)
        {
            var m = paramTypes != null ? type.GetMethod(method, paramTypes) : type.GetMethod(method);
            if (m == null)
            {
                Monitor.Log($"Untranslated Stardew: Target method {type.Name}.{method} signature mismatch or not found.", LogLevel.Warn);
            }
        }

        // Validate targeted private fields bound by Harmony patches
        var fieldTargets = new (Type Type, string FieldName, Type ExpectedType)[]
        {
            (typeof(StardewValley.Menus.LevelUpMenu), "leftProfessionDescription", typeof(System.Collections.Generic.List<string>)),
            (typeof(StardewValley.Menus.LevelUpMenu), "rightProfessionDescription", typeof(System.Collections.Generic.List<string>)),
            (typeof(StardewValley.Menus.LevelUpMenu), "professionsToChoose", typeof(System.Collections.Generic.List<int>)),
            (typeof(StardewValley.Menus.LevelUpMenu), "leftProfessionColor", typeof(Microsoft.Xna.Framework.Color)),
            (typeof(StardewValley.Menus.LevelUpMenu), "rightProfessionColor", typeof(Microsoft.Xna.Framework.Color)),
            (typeof(StardewValley.Menus.SkillsPage), "hoverTitle", typeof(string)),
            (typeof(StardewValley.Menus.PowersTab), "hoverText", typeof(string)),
            (typeof(StardewValley.Menus.PowersTab), "descriptionText", typeof(string)),
            (typeof(StardewValley.Menus.PowersTab), "powers", typeof(System.Collections.Generic.List<System.Collections.Generic.List<StardewValley.Menus.ClickableTextureComponent>>))
        };

        foreach (var (type, fieldName, expectedType) in fieldTargets)
        {
            var f = type.GetField(fieldName, System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Public);
            if (f == null || !expectedType.IsAssignableFrom(f.FieldType))
            {
                Monitor.Log($"Untranslated Stardew: Target field {type.Name}.{fieldName} ({expectedType.Name}) mismatch or not found.", LogLevel.Warn);
            }
        }
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            Helper.Events.GameLoop.GameLaunched -= OnGameLaunched;
            Helper.Events.Content.LocaleChanged -= OnLocaleChanged;
            Helper.Events.Content.AssetsInvalidated -= OnAssetsInvalidated;

            _contentProvider?.Dispose();
            _contentProvider = null;
            _nameResolver = null;

            _harmony?.UnpatchAll(ModManifest.UniqueID);
            _harmony = null;
            Instance = null;
        }

        base.Dispose(disposing);
    }
}

/// <summary>
/// Minimal interface for Generic Mod Config Menu integration.
/// </summary>
public interface IGenericModConfigMenuApi
{
    void Register(IManifest mod, Action reset, Action save, bool titleScreenOnly = false);
    void AddTextOption(IManifest mod, Func<string> getValue, Action<string> setValue, Func<string> name, Func<string>? tooltip = null, string[]? allowedValues = null, Func<string, string>? formatAllowedValue = null, string? fieldId = null);
    void AddBoolOption(IManifest mod, Func<bool> getValue, Action<bool> setValue, Func<string> name, Func<string>? tooltip = null, string? fieldId = null);
}
